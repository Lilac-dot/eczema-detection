def youden_ci(se, sp, npos, nneg, seed):
    """Class-stratified bootstrap CI for Youden's J = Se + Sp - 1."""
    rng = np.random.default_rng(seed)
    se_b = rng.binomial(npos, se, B_BOOT) / npos
    sp_b = rng.binomial(nneg, sp, B_BOOT) / nneg
    j_b = se_b + sp_b - 1
    return se + sp - 1, float(np.percentile(j_b, 2.5)), float(np.percentile(j_b, 97.5))


def classify(arch, acc, fp32_acc, j_lo):
    retention = acc / fp32_acc
    if j_lo <= 0:
        return "collapsed", retention
    if retention >= MLPERF_TARGET.get(arch, MLPERF_LIGHT):
        return "backend-stable", retention
    return "degraded", retention


