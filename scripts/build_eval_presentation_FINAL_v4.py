def _set_run(run, text, size=18, bold=False, italic=False, color=BODY, font=BODY_FONT):
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = color
    run.font.name = font


def textbox(slide, left, top, width, height, text, size=18, bold=False, italic=False,
            color=BODY, font=BODY_FONT, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP,
            line_spacing=1.0, wrap=True):
    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.word_wrap = wrap
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    p = tf.paragraphs[0]
    p.alignment = align
    if line_spacing:
        p.line_spacing = line_spacing
    _set_run(p.add_run(), text, size, bold, italic, color, font)
    return box


def _enable_bullet(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    pPr.set("indent", "-228600")
    pPr.set("marL", "228600")
    pPr.append(pPr.makeelement(qn("a:buFont"), {"typeface": "Arial"}))
    pPr.append(pPr.makeelement(qn("a:buChar"), {"char": "•"}))


def multiline(slide, left, top, width, height, lines, anchor=MSO_ANCHOR.TOP):
    """lines: list of dicts. A dict has either "text" (one run) or "runs" (list of dicts with
    text/size/bold/italic/color/font/link) plus paragraph keys (space_after, align, bullet)."""
    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    for i, ln in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = ln.get("align", PP_ALIGN.LEFT)
        p.line_spacing = ln.get("line_spacing", 1.15)
        p.space_after = Pt(ln.get("space_after", 8))
        if ln.get("bullet"):
            _enable_bullet(p)
        runs = ln.get("runs") or [ln]
        for rd in runs:
            r = p.add_run()
            _set_run(r, rd["text"], rd.get("size", ln.get("size", 16)),
                     rd.get("bold", ln.get("bold", False)), rd.get("italic", ln.get("italic", False)),
                     rd.get("color", ln.get("color", BODY)), rd.get("font", ln.get("font", BODY_FONT)))
            if rd.get("link"):
                r.hyperlink.address = rd["link"]
    return box


