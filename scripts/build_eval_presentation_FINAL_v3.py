        j, lo, hi = youden_ci(se, sp, VAL_NPOS, VAL_NNEG, seed=100 + i)
        status, r = classify(a, m["accuracy"], FP32_VAL[a], lo)
        row[tag] = dict(acc=m["accuracy"], se=se, sp=sp, j=j, lo=lo, hi=hi, r=r, status=status)
