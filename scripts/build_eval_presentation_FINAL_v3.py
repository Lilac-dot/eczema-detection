def _style_cell(cell, fill):
    cell.fill.solid()
    cell.fill.fore_color.rgb = fill
    cell.vertical_anchor = MSO_ANCHOR.MIDDLE
    cell.margin_left = Pt(6); cell.margin_right = Pt(6)
    cell.margin_top = Pt(2); cell.margin_bottom = Pt(2)


def make_table(slide, left, top, width, height, headers, rows, col_widths_frac,
               font_size=14, header_fill=DARK, header_color=WHITE, alt_row=ROW_ALT,
               cell_colors=None, first_col_align=PP_ALIGN.LEFT, other_align=PP_ALIGN.RIGHT):
    """rows: list of lists; a cell may be a str or a list of run dicts (text/bold/link/...)."""
    n_rows, n_cols = len(rows) + 1, len(headers)
    gshape = slide.shapes.add_table(n_rows, n_cols, left, top, width, height)
    tbl = gshape.table
    for c, frac in enumerate(col_widths_frac):
        tbl.columns[c].width = Emu(int(width * frac))
    for ri in range(n_rows):
        tbl.rows[ri].height = Emu(int(height / n_rows))
    for c, h in enumerate(headers):
        cell = tbl.cell(0, c)
        _style_cell(cell, header_fill)
        p = cell.text_frame.paragraphs[0]
        p.alignment = first_col_align if c == 0 else other_align
        _set_run(p.add_run(), h, font_size, True, False, header_color, BODY_FONT)
    for ri, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = tbl.cell(ri + 1, c)
            _style_cell(cell, alt_row if ri % 2 == 1 else CARD_BG)
            p = cell.text_frame.paragraphs[0]
            p.alignment = first_col_align if c == 0 else other_align
            colored = cell_colors and (ri, c) in cell_colors
            if isinstance(val, list):
                for rd in val:
                    if rd.get("newline"):
                        p = cell.text_frame.add_paragraph()
                        p.alignment = first_col_align if c == 0 else other_align
                    r = p.add_run()
                    _set_run(r, rd["text"], rd.get("size", font_size), rd.get("bold", False),
                             rd.get("italic", False), rd.get("color", BODY), BODY_FONT)
                    if rd.get("link"):
                        r.hyperlink.address = rd["link"]
            else:
                _set_run(p.add_run(), str(val), font_size, bool(colored), False,
                         cell_colors[(ri, c)] if colored else BODY, BODY_FONT)
    return gshape


